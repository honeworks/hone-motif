// Writes what the library derives from its sources (decision D-002): every asset's props.schema.json from
// its zod schema, src/Root.tsx (the registry) from the asset.json files, and themes.json from
// shared/themes.ts. With --check it writes nothing and fails when any of them is out of date, or when an
// asset's default props or samples do not pass its schema (design §11).
import fs from 'node:fs';
import path from 'node:path';
import {z} from 'zod';
import {THEMES} from '../shared/themes.ts';

const ROOT = path.resolve(import.meta.dirname, '..');
const TICKS = 32;
type Meta = {id: string; kind: string; duration: {default_ms: number}; props: object; samples?: Record<string, object>;
  transition?: {fx_blend: string}};

const json = (value: unknown) => JSON.stringify(value, null, 1) + '\n';

const assetIds = (): string[] =>
  fs.readdirSync(path.join(ROOT, 'assets')).filter((d) => fs.existsSync(path.join(ROOT, 'assets', d, 'asset.json'))).sort();

const rootSource = (metas: Meta[]): string => {
  const imports = metas.map((m, i) =>
    `import {Component as C${i}} from '../assets/${m.id}/composition.tsx';\nimport {schema as S${i}} from '../assets/${m.id}/schema.ts';`);
  const entries = metas.map((m, i) => {
    const frames = Math.round((m.duration.default_ms * TICKS) / 1000);
    const blend = m.transition?.fx_blend === 'screen' ? 'screen' : 'normal';
    return `  {id: '${m.id}', kind: '${m.kind}', frames: ${frames}, blend: '${blend}', Component: C${i}, schema: S${i},\n   props: ${JSON.stringify(m.props)}},`;
  });
  return [
    '// Generated by scripts/export.ts from assets/*/asset.json; do not edit (npm run export).',
    "import React from 'react';",
    "import {Entries, type Entry} from '../shared/frame.tsx';",
    ...imports,
    '',
    'const ENTRIES: Entry[] = [',
    ...entries,
    '];',
    '',
    'export const RemotionRoot: React.FC = () => <>{ENTRIES.map((e) => <Entries key={e.id} entry={e} />)}</>;',
    '',
  ].join('\n');
};

const outputs = new Map<string, string>();
const problems: string[] = [];
const metas: Meta[] = [];
for (const id of assetIds()) {
  const meta: Meta = JSON.parse(fs.readFileSync(path.join(ROOT, 'assets', id, 'asset.json'), 'utf8'));
  const {schema} = (await import(`../assets/${id}/schema.ts`)) as {schema: z.ZodType};
  outputs.set(`assets/${id}/props.schema.json`, json(z.toJSONSchema(schema, {io: 'input', target: 'draft-2020-12'})));
  for (const [name, props] of [['props', meta.props], ...Object.entries(meta.samples ?? {})] as [string, object][]) {
    const result = schema.safeParse(props);
    if (!result.success) problems.push(`${id}: ${name} do not pass the schema: ${result.error.message}`);
  }
  metas.push(meta);
}
outputs.set('src/Root.tsx', rootSource(metas));
outputs.set('themes.json', json(THEMES));

const check = process.argv.includes('--check');
for (const [file, content] of outputs) {
  const full = path.join(ROOT, file);
  const current = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
  if (current === content) continue;
  if (check) problems.push(`${file} is out of date: run \`npm run export\` in library/`);
  else fs.writeFileSync(full, content);
}
for (const p of problems) console.error(p);
console.log(`${metas.length} assets, ${problems.length} problems`);
process.exit(problems.length ? 1 : 0);
